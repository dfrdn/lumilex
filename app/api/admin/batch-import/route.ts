import { getSession } from '@/lib/session';
import { NextRequest, NextResponse } from 'next/server';
import { getSupabaseServerAuthClient } from '@/lib/supabase-server';
import { getEntityConfig, MATTER_TYPE_CODES } from '@/lib/admin/entity-config';
import { fetchMatterTypeCodes } from '@/lib/enum-options';
import { allocateClientCode } from '@/lib/clients/allocate-client-code';
import { mintId } from '@/lib/ids';
import { TENANT_TABLES } from '@/lib/tenancy/tables.generated';
import { refuseInDemo } from '@/lib/demo/guard';

async function assertAdmin() {
  const session = await getSession();
  if (!session?.user?.role || !['admin', 'super_user', 'finance'].includes(session.user.role)) {
    return null;
  }
  return session;
}

// ---------------------------------------------------------------------------
// POST  /api/admin/batch-import
// Batch-insert rows into an entity table.
// Body: { entity: string, rows: Record<string, string>[] }
// ---------------------------------------------------------------------------
export async function POST(req: NextRequest) {
  const session = await assertAdmin();
  if (!session) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  }

  const body = await req.json();
  const { entity, rows } = body as {
    entity: string;
    rows: Record<string, string>[];
  };

  if (!entity || !Array.isArray(rows) || rows.length === 0) {
    return NextResponse.json(
      { error: 'entity and a non-empty rows array are required' },
      { status: 400 },
    );
  }

  const config = getEntityConfig(entity);
  if (!config) {
    return NextResponse.json({ error: `Unknown entity: ${entity}` }, { status: 400 });
  }
  // A global table (ph_holidays) is read by every firm on the instance, so a
  // demo visitor's edit would outlive the nightly reset and reach past the demo.
  if (!TENANT_TABLES.has(config.dbTable)) {
    const demoRefusal = await refuseInDemo(session.firmId, 'Editing shared reference data');
    if (demoRefusal) return demoRefusal;
  }

  const supabase = await getSupabaseServerAuthClient();
  const errors: { row: number; message: string }[] = [];
  let created = 0;

  // For matters: pre-fetch client codes and matter counts per client
  let clientCodeLookup: Record<string, string> = {};
  let matterCountByClient: Record<string, number> = {};
  let matterTypeCodes: Record<string, number> = {};
  if (entity === 'matters') {
    const [clientsResult, mattersResult, dbCodes] = await Promise.all([
      supabase.from('clients').select('name, client_code'),
      supabase.from('matters').select('client_name'),
      fetchMatterTypeCodes(session.firmId),
    ]);
    matterTypeCodes = dbCodes;
    for (const c of clientsResult.data ?? []) {
      if (c.name && c.client_code) clientCodeLookup[c.name] = c.client_code;
    }
    for (const m of mattersResult.data ?? []) {
      if (m.client_name) {
        matterCountByClient[m.client_name] = (matterCountByClient[m.client_name] || 0) + 1;
      }
    }
  }

  // Tables with a SERIAL/bigserial primary key (declared via primaryKeyColumn)
  // have no notion_id column at all, so synthesizing one fails 42703 on every
  // row. Same rule as the single-row POST in /api/admin/[entity].
  const usesNotionIdPk = (config.primaryKeyColumn ?? 'notion_id') === 'notion_id';

  // Process sequentially to keep auto-increment consistent
  for (let i = 0; i < rows.length; i++) {
    const inputRow = rows[i];

    // Map field keys to supabase columns
    const dbRow: Record<string, unknown> = usesNotionIdPk
      ? { notion_id: mintId(entity) }
      : {};
    // firm_id is stamped explicitly: this handler writes through the authed
    // client, which (unlike getServiceDbForFirm) does not inject it, and the
    // column's transitional default is gone. Asked of the registry rather than
    // stamped unconditionally, because one admin entity (ph_holidays) is a
    // global table with no firm_id column.
    if (TENANT_TABLES.has(config.dbTable)) dbRow.firm_id = session.firmId;
    for (const f of config.fields) {
      if (inputRow[f.key] !== undefined && inputRow[f.key] !== '' && !f.autoGenerated) {
        dbRow[f.supabaseColumn] = inputRow[f.key];
      }
    }

    // Auto-generate client code — allocate atomically per row so a concurrent
    // create elsewhere can't hand out the same number.
    if (entity === 'clients') {
      dbRow.client_code = await allocateClientCode(supabase, session.firmId);
    }

    // Auto-derive matter code
    if (entity === 'matters' && dbRow.client_name && dbRow.type) {
      const cName = dbRow.client_name as string;
      const cCode = clientCodeLookup[cName] || '0';
      const typeName = dbRow.type as string;
      const tCode = matterTypeCodes[typeName] ?? MATTER_TYPE_CODES[typeName] ?? 0;
      const seq = (matterCountByClient[cName] || 0) + 1;
      dbRow.matter_code = `${cCode}-${tCode}-${(matterCountByClient[cName] || 0)}`;
      matterCountByClient[cName] = seq; // increment for next row
    }

    const { error } = await supabase
      .from(config.dbTable)
      .insert(dbRow)
      .select()
      .single();

    if (error) {
      errors.push({ row: i + 1, message: error.message });
    } else {
      created++;
    }
  }

  return NextResponse.json({ created, errors });
}
