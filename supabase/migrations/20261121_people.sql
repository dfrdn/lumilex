-- ── Move the rows ──────────────────────────────────────────────────────────
DO $$
BEGIN
  IF to_regclass('public.corporation_persons') IS NOT NULL
     AND (SELECT relkind FROM pg_class WHERE oid = 'public.corporation_persons'::regclass) = 'r' THEN

    -- A person may hold a role at a company once. Intake autosaves on every
    -- blur, and a second blur before the first POST returned created a twin
    -- row. Drop a twin only while its earlier copy exists and nothing is
    -- attached to it, so this never removes a real person.
    DELETE FROM public.corporation_persons d
    WHERE NOT EXISTS (SELECT 1 FROM public.corporation_files f WHERE f.person_id = d.id)
      AND public.corporation_person_identity(d.is_juridical, d.entity_name, d.first_name, d.last_name) <> ''
      AND d.is_current
      AND EXISTS (
        SELECT 1 FROM public.corporation_persons k
        WHERE k.id < d.id
          AND k.firm_id = d.firm_id
          AND k.corporation_id = d.corporation_id
          AND k.role = d.role
          AND k.is_current
          AND coalesce(lower(btrim(k.position_title)), '') = coalesce(lower(btrim(d.position_title)), '')
          AND public.corporation_person_identity(k.is_juridical, k.entity_name, k.first_name, k.last_name)
            = public.corporation_person_identity(d.is_juridical, d.entity_name, d.first_name, d.last_name)
      );

    CREATE TEMP TABLE _pm ON COMMIT DROP AS
    SELECT cp.*,
           public.corporation_person_identity(cp.is_juridical, cp.entity_name, cp.first_name, cp.last_name) AS nm,
           nullif(regexp_replace(coalesce(cp.tin, ''), '\D', '', 'g'), '') AS tin_d
    FROM public.corporation_persons cp;

    -- One person per full name within a firm; a row with no name is its own
    -- person. Never across firms.
    CREATE TEMP TABLE _pk ON COMMIT DROP AS
    SELECT m.id AS row_id, m.firm_id,
           m.firm_id::text || '|' || CASE WHEN m.nm = '' THEN 'row:' || m.id ELSE m.nm END AS key
    FROM _pm m;
    CREATE TEMP TABLE _pid ON COMMIT DROP AS
    SELECT key, min(firm_id::text)::uuid AS firm_id, gen_random_uuid()::text AS pid
    FROM _pk GROUP BY key;

    INSERT INTO public.people (id, firm_id, is_juridical, first_name, last_name, entity_name, entity_type, entity_registration_no,
                               representative_name, representative_title, nationality, gender, residential_address,
                               tin, passport_number, esap_no, created_at, updated_at)
    SELECT DISTINCT ON (k.key)
           p.pid, m.firm_id, m.is_juridical, m.first_name, m.last_name, m.entity_name, m.entity_type, m.entity_registration_no,
           m.representative_name, m.representative_title, m.nationality, m.gender, m.residential_address,
           m.tin, m.passport_number, m.esap_no, m.created_at, m.updated_at
    FROM _pm m
    JOIN _pk k ON k.row_id = m.id
    JOIN _pid p ON p.key = k.key
    ORDER BY k.key,
             num_nonnulls(m.tin, m.passport_number, m.residential_address, m.nationality, m.gender, m.esap_no) DESC,
             m.updated_at DESC;

    -- Fill any identity detail the chosen row lacked from the person's other rows.
    UPDATE public.people p SET
      nationality = coalesce(p.nationality, x.nationality),
      gender = coalesce(p.gender, x.gender),
      residential_address = coalesce(p.residential_address, x.residential_address),
      passport_number = coalesce(p.passport_number, x.passport_number),
      esap_no = coalesce(p.esap_no, x.esap_no)
    FROM (
      SELECT pi.pid,
             max(m.nationality) AS nationality, max(m.gender) AS gender, max(m.residential_address) AS residential_address,
             max(m.passport_number) AS passport_number, max(m.esap_no) AS esap_no
      FROM _pm m JOIN _pk k ON k.row_id = m.id JOIN _pid pi ON pi.key = k.key
      GROUP BY pi.pid
    ) x
    WHERE x.pid = p.id;

    -- The TIN used most often wins; any other goes into notes for review.
    UPDATE public.people p SET
      tin = x.tin_mode,
      notes = CASE WHEN x.others IS NOT NULL
                   THEN 'Other TIN on record (check which is right): ' || x.others
                   ELSE p.notes END
    FROM (
      SELECT pi.pid,
             (SELECT m2.tin FROM _pm m2 JOIN _pk k2 ON k2.row_id = m2.id
              WHERE k2.key = pi.key AND m2.tin IS NOT NULL
              GROUP BY m2.tin ORDER BY count(*) DESC, m2.tin LIMIT 1) AS tin_mode,
             (SELECT string_agg(DISTINCT m3.tin, ', ') FROM _pm m3 JOIN _pk k3 ON k3.row_id = m3.id
              WHERE k3.key = pi.key AND m3.tin_d IS NOT NULL
                AND m3.tin_d <> (SELECT regexp_replace(m4.tin, '\D', '', 'g') FROM _pm m4 JOIN _pk k4 ON k4.row_id = m4.id
                                 WHERE k4.key = pi.key AND m4.tin IS NOT NULL
                                 GROUP BY m4.tin ORDER BY count(*) DESC, m4.tin LIMIT 1)) AS others
      FROM _pid pi
      WHERE pi.key NOT LIKE '%|row:%'
    ) x
    WHERE x.pid = p.id AND x.tin_mode IS NOT NULL;

    INSERT INTO public.corporation_roles (id, firm_id, corporation_id, person_id, role, position_title, term_start, term_end, is_current,
                                          sort_order, shares_subscribed_amount, shares_paid_amount, shares_subscribed_count,
                                          share_class, created_at, updated_at)
    OVERRIDING SYSTEM VALUE
    SELECT m.id, m.firm_id, m.corporation_id, p.pid, m.role, m.position_title, m.term_start, m.term_end, m.is_current,
           m.sort_order, m.shares_subscribed_amount, m.shares_paid_amount, m.shares_subscribed_count,
           m.share_class, m.created_at, m.updated_at
    FROM _pm m
    JOIN _pk k ON k.row_id = m.id
    JOIN _pid p ON p.key = k.key;

    PERFORM setval(pg_get_serial_sequence('public.corporation_roles', 'id'),
                   greatest(coalesce((SELECT max(id) FROM public.corporation_roles), 1),
                            (SELECT last_value FROM public.corporation_persons_id_seq)));

    ALTER TABLE public.corporation_files DROP CONSTRAINT IF EXISTS corporation_files_person_id_fkey;
    DROP TABLE public.corporation_persons;
  END IF;
END $$;

