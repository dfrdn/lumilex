CREATE OR REPLACE FUNCTION public.sync_person_subject() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  nm text := CASE WHEN NEW.is_juridical THEN coalesce(NEW.entity_name, '') ELSE btrim(NEW.first_name || ' ' || NEW.last_name) END;
BEGIN
  IF NEW.firm_id IS NULL THEN RETURN NEW; END IF;
  INSERT INTO public.subjects (id, firm_id, type, name, identifier)
  VALUES (NEW.id, NEW.firm_id, 'person', nm, coalesce(NEW.tin, NEW.passport_number))
  ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, identifier = EXCLUDED.identifier, updated_at = now()
    WHERE (public.subjects.name, public.subjects.identifier) IS DISTINCT FROM (EXCLUDED.name, EXCLUDED.identifier);
  RETURN NEW;
END $$;
