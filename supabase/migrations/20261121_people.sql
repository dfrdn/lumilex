-- People: one record per human, per firm, with roles in any number of that
-- firm's companies.
--
-- corporation_persons held one row per (person, role, company): a board of
-- six read as seventeen entries, and the same human was re-typed — ID, TIN,
-- address — in every company they sat in. Now:
--   people             one row per human (a subject of type 'person')
--   corporation_roles  what they are in a company — director, president,
--                      stockholder with their shares — keeping the old row ids
--   corporation_persons  a read-only view joining the two, with the old
--                      columns plus person_id, so every reader keeps working.
--
-- Writes go through three functions rather than through the view: a view
-- carries SELECT only (a write grant on one is a second door into its base
-- tables), so `corporation_person_insert / _update / _delete` hold the rule
-- that decides who is who. They run as the caller, so RLS on people and
-- corporation_roles is the gate as for any other write.
--
-- The move groups rows by full name within a firm. A name carrying two TINs
-- keeps the commoner and writes the other into the person's notes for review
-- rather than splitting one human in two.

-- ── Identity ───────────────────────────────────────────────────────────────
-- Normalized display identity: entity name for juridical persons, otherwise
-- first + last; trimmed, whitespace collapsed, lower-cased.
CREATE OR REPLACE FUNCTION public.corporation_person_identity(
  p_is_juridical boolean,
  p_entity_name text,
  p_first_name text,
  p_last_name text
) RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT lower(regexp_replace(btrim(
    CASE WHEN p_is_juridical THEN coalesce(p_entity_name, '')
         ELSE coalesce(p_first_name, '') || ' ' || coalesce(p_last_name, '')
    END), '\s+', ' ', 'g'))
$$;

