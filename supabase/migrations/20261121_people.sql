-- ── Who is who ─────────────────────────────────────────────────────────────
-- Who a new role belongs to: the same name already at this company (with no
-- clashing TIN or passport), else anyone in the firm with the same name and
-- the same TIN or passport. A name alone never joins two companies' people —
-- two different people of one name stay two.
CREATE OR REPLACE FUNCTION public.match_person(
  p_firm uuid, p_corp text, p_jur boolean, p_entity text, p_first text, p_last text, p_tin text, p_pass text
) RETURNS text
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE
  v_nm text := public.corporation_person_identity(coalesce(p_jur, false), p_entity, p_first, p_last);
  v_tin text := nullif(regexp_replace(coalesce(p_tin, ''), '\D', '', 'g'), '');
  v_pass text := nullif(upper(regexp_replace(coalesce(p_pass, ''), '\s', '', 'g')), '');
  found text;
BEGIN
  IF v_nm = '' THEN RETURN NULL; END IF;
  SELECT p.id INTO found
  FROM public.corporation_roles r JOIN public.people p ON p.id = r.person_id
  WHERE r.corporation_id = p_corp
    AND r.firm_id = p_firm AND p.firm_id = p_firm
    AND public.corporation_person_identity(p.is_juridical, p.entity_name, p.first_name, p.last_name) = v_nm
    AND (v_tin IS NULL OR p.tin IS NULL OR regexp_replace(p.tin, '\D', '', 'g') = v_tin)
    AND (v_pass IS NULL OR p.passport_number IS NULL OR upper(regexp_replace(p.passport_number, '\s', '', 'g')) = v_pass)
  LIMIT 1;
  IF found IS NOT NULL OR (v_tin IS NULL AND v_pass IS NULL) THEN RETURN found; END IF;
  SELECT p.id INTO found
  FROM public.people p
  WHERE p.firm_id = p_firm
    AND public.corporation_person_identity(p.is_juridical, p.entity_name, p.first_name, p.last_name) = v_nm
    AND ((v_tin IS NOT NULL AND regexp_replace(coalesce(p.tin, ''), '\D', '', 'g') = v_tin)
      OR (v_pass IS NOT NULL AND upper(regexp_replace(coalesce(p.passport_number, ''), '\s', '', 'g')) = v_pass))
  LIMIT 1;
  RETURN found;
END $$;

-- A person with no roles, no matter links and nothing held is removed.
CREATE OR REPLACE FUNCTION public.drop_orphan_person(p_id text) RETURNS void
LANGUAGE sql SET search_path = '' AS $$
  DELETE FROM public.people p
  WHERE p.id = p_id
    AND NOT EXISTS (SELECT 1 FROM public.corporation_roles r WHERE r.person_id = p.id)
    AND NOT EXISTS (SELECT 1 FROM public.matter_subjects ms WHERE ms.subject_id = p.id)
    AND NOT EXISTS (SELECT 1 FROM public.subjects s WHERE s.holder_subject_id = p.id);
$$;

-- A new person from a role's identity columns.
CREATE OR REPLACE FUNCTION public.new_person_from(p_firm uuid, r public.corporation_persons) RETURNS text
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  pid text := gen_random_uuid()::text;
BEGIN
  INSERT INTO public.people (id, firm_id, is_juridical, first_name, last_name, entity_name, entity_type, entity_registration_no,
                             representative_name, representative_title, nationality, gender, residential_address,
                             tin, passport_number, esap_no)
  VALUES (pid, p_firm, coalesce(r.is_juridical, false), coalesce(r.first_name, ''), coalesce(r.last_name, ''), r.entity_name,
          r.entity_type, r.entity_registration_no, r.representative_name, r.representative_title, r.nationality,
          r.gender, r.residential_address, r.tin, r.passport_number, r.esap_no);
  RETURN pid;
END $$;

-- Insert a role, in the view's shape. A row that names its person_id adds a
-- role to that person as is, without matching or touching their details
-- ("Add role" on a person card). Otherwise the role joins the person
-- match_person finds — filling gaps in their details, never overwriting — or
-- a new person. The firm is the company's, read under the caller's own RLS.
-- Returns the new role id.
CREATE OR REPLACE FUNCTION public.corporation_person_insert(p_row jsonb) RETURNS integer
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  n public.corporation_persons := jsonb_populate_record(null::public.corporation_persons, p_row);
  v_firm uuid;
  pid text;
  rid integer;
BEGIN
  SELECT c.firm_id INTO v_firm FROM public.corporations c WHERE c.id = n.corporation_id;
  IF v_firm IS NULL THEN
    RAISE EXCEPTION 'corporation not found' USING ERRCODE = '42501';
  END IF;

  IF n.person_id IS NOT NULL AND EXISTS (SELECT 1 FROM public.people WHERE id = n.person_id AND firm_id = v_firm) THEN
    pid := n.person_id;
  ELSE
    pid := public.match_person(v_firm, n.corporation_id, n.is_juridical, n.entity_name, n.first_name, n.last_name, n.tin, n.passport_number);
    IF pid IS NULL THEN
      pid := public.new_person_from(v_firm, n);
    ELSE
      UPDATE public.people SET
        nationality = coalesce(nationality, n.nationality),
        gender = coalesce(gender, n.gender),
        residential_address = coalesce(residential_address, n.residential_address),
        tin = coalesce(tin, n.tin),
        passport_number = coalesce(passport_number, n.passport_number),
        esap_no = coalesce(esap_no, n.esap_no),
        entity_type = coalesce(entity_type, n.entity_type),
        entity_registration_no = coalesce(entity_registration_no, n.entity_registration_no),
        representative_name = coalesce(representative_name, n.representative_name),
        representative_title = coalesce(representative_title, n.representative_title),
        updated_at = now()
      WHERE id = pid;
    END IF;
  END IF;

  INSERT INTO public.corporation_roles (firm_id, corporation_id, person_id, role, position_title, term_start, term_end, is_current,
                                        sort_order, shares_subscribed_amount, shares_paid_amount, shares_subscribed_count, share_class)
  VALUES (v_firm, n.corporation_id, pid, n.role, n.position_title, n.term_start, n.term_end, coalesce(n.is_current, true),
          coalesce(n.sort_order, 0), n.shares_subscribed_amount, n.shares_paid_amount, n.shares_subscribed_count, n.share_class)
  RETURNING id INTO rid;
  RETURN rid;
END $$;

-- Update a role, in the view's shape: the keys of p_patch overwrite the role
-- as it stands. A detail edit on a role edits the person. A rename joins the
-- person the new name belongs to; splits off a new person only if the old one
-- still holds other roles; and otherwise renames in place. A person left with
-- no role is deleted. Returns the role id, or null when the role was not found.
CREATE OR REPLACE FUNCTION public.corporation_person_update(p_id integer, p_patch jsonb) RETURNS integer
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  o public.corporation_persons;
  n public.corporation_persons;
  pid text;
  matched text;
BEGIN
  SELECT * INTO o FROM public.corporation_persons WHERE id = p_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
  n := jsonb_populate_record(o, p_patch - 'id' - 'firm_id' - 'person_id' - 'corporation_id');
  pid := o.person_id;

  IF public.corporation_person_identity(coalesce(n.is_juridical, false), n.entity_name, n.first_name, n.last_name)
     <> public.corporation_person_identity(coalesce(o.is_juridical, false), o.entity_name, o.first_name, o.last_name) THEN
    matched := public.match_person(o.firm_id, o.corporation_id, n.is_juridical, n.entity_name, n.first_name, n.last_name, n.tin, n.passport_number);
    IF matched IS NOT NULL AND matched <> o.person_id THEN
      pid := matched;
      UPDATE public.people SET
        nationality = coalesce(nationality, n.nationality),
        gender = coalesce(gender, n.gender),
        residential_address = coalesce(residential_address, n.residential_address),
        tin = coalesce(tin, n.tin),
        passport_number = coalesce(passport_number, n.passport_number),
        esap_no = coalesce(esap_no, n.esap_no),
        updated_at = now()
      WHERE id = pid;
    ELSIF EXISTS (SELECT 1 FROM public.corporation_roles r WHERE r.person_id = o.person_id AND r.id <> o.id) THEN
      pid := public.new_person_from(o.firm_id, n);
    END IF;
  END IF;

  IF pid = o.person_id THEN
    UPDATE public.people SET
      is_juridical = coalesce(n.is_juridical, false),
      first_name = coalesce(n.first_name, ''),
      last_name = coalesce(n.last_name, ''),
      entity_name = n.entity_name,
      entity_type = n.entity_type,
      entity_registration_no = n.entity_registration_no,
      representative_name = n.representative_name,
      representative_title = n.representative_title,
      nationality = n.nationality,
      gender = n.gender,
      residential_address = n.residential_address,
      tin = n.tin,
      passport_number = n.passport_number,
      esap_no = n.esap_no,
      updated_at = now()
    WHERE id = o.person_id
      AND (is_juridical, first_name, last_name, entity_name, entity_type, entity_registration_no, representative_name,
           representative_title, nationality, gender, residential_address, tin, passport_number, esap_no)
          IS DISTINCT FROM
          (coalesce(n.is_juridical, false), coalesce(n.first_name, ''), coalesce(n.last_name, ''), n.entity_name,
           n.entity_type, n.entity_registration_no, n.representative_name, n.representative_title, n.nationality,
           n.gender, n.residential_address, n.tin, n.passport_number, n.esap_no);
  END IF;

  UPDATE public.corporation_roles SET
    person_id = pid,
    role = n.role,
    position_title = n.position_title,
    term_start = n.term_start,
    term_end = n.term_end,
    is_current = coalesce(n.is_current, true),
    sort_order = coalesce(n.sort_order, 0),
    shares_subscribed_amount = n.shares_subscribed_amount,
    shares_paid_amount = n.shares_paid_amount,
    shares_subscribed_count = n.shares_subscribed_count,
    share_class = n.share_class,
    updated_at = now()
  WHERE id = o.id;

  IF pid <> o.person_id THEN PERFORM public.drop_orphan_person(o.person_id); END IF;
  RETURN o.id;
END $$;

-- Delete a role; its person goes too when that was their last one.
CREATE OR REPLACE FUNCTION public.corporation_person_delete(p_id integer) RETURNS integer
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
  v_person text;
BEGIN
  DELETE FROM public.corporation_roles WHERE id = p_id RETURNING person_id INTO v_person;
  IF v_person IS NULL THEN RETURN NULL; END IF;
  PERFORM public.drop_orphan_person(v_person);
  RETURN p_id;
END $$;

-- Invoker functions: RLS on people and corporation_roles decides what each
-- caller may touch. Staff and the service role call them; nobody else.
