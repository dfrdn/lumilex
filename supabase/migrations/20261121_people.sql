-- ── The read view ──────────────────────────────────────────────────────────
-- Invoker, so it shows no more than RLS on people and corporation_roles
-- would; SELECT only; firm_id last, for the service-role facade.
CREATE OR REPLACE VIEW public.corporation_persons WITH (security_invoker = on) AS
SELECT r.id, r.corporation_id, r.role,
       p.first_name, p.last_name, p.nationality, p.gender, p.residential_address, p.tin, p.passport_number, p.esap_no,
       r.shares_subscribed_amount, r.shares_paid_amount, r.position_title, r.term_start, r.term_end, r.is_current,
       r.sort_order, r.created_at, r.updated_at,
       p.is_juridical, p.entity_name, p.entity_type, p.entity_registration_no, p.representative_name, p.representative_title,
       r.share_class, r.shares_subscribed_count,
       p.id AS person_id,
       r.firm_id
FROM public.corporation_roles r
JOIN public.people p ON p.id = r.person_id AND p.firm_id = r.firm_id;

REVOKE ALL ON public.corporation_persons FROM PUBLIC, anon, authenticated, service_role;
