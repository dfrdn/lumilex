/**
 * The operator's firm-provisioning config: what a new tenant is, expressed as
 * one JSON file that `scripts/provision-firm.ts` reads.
 *
 * A file rather than flags. Fifteen-odd fields, several of them nested (the
 * palette, the email identity, the document roots), do not survive a command
 * line legibly — and the interesting property of provisioning is that it is
 * re-runnable. A file is the record of what a firm was provisioned with: it can
 * be reviewed before it is run, kept in the ops repo beside the firm's other
 * onboarding paperwork, and replayed verbatim when a step failed halfway. A
 * shell-history reconstruction of twenty flags is none of those things.
 *
 * No secret is in it. The first admin's password is generated by the script and
 * printed once, or supplied through PROVISION_ADMIN_PASSWORD — so the config
 * file is safe to commit, which is the whole point of it being a file.
 *
 * This module is pure: it parses and validates, and touches nothing. The two
 * shapes it cannot know on its own — the `firms.slug` and
 * `firm_invoice_settings.invoice_prefix` CHECK patterns — are read from the
 * database at runtime through `provisioning_patterns()` and applied by
 * {@link assertMatchesPattern}, so a widened constraint never leaves the script
 * rejecting input the database would have taken.
 */

import { z } from 'zod';
import { FEATURE_KEYS } from '@/lib/firm/features';

const hex = z
  .string()
  .regex(/^#[0-9a-fA-F]{6}$/, 'Use a 6-digit hex colour, e.g. "#0F2A44"');

/**
 * A hostname, not a URL and not an email domain. Lowercased on parse because
 * `firm_domains` has a CHECK that the stored value equals its own lowercase.
 */
const hostname = z
  .string()
  .min(1)
  .transform((value) => value.trim().toLowerCase())
  .refine((value) => !value.includes('/') && !value.includes('@'), {
    message: 'Give a bare hostname — no scheme, path, or @',
  })
  .refine((value) => /^[a-z0-9.-]+$/.test(value), {
    message: 'A hostname may only contain letters, digits, dots, and hyphens',
  });

export const provisionConfigSchema = z.object({
  /** Validated against the live firms_slug_check pattern before insert. */
  slug: z.string().min(1).transform((v) => v.trim().toLowerCase()),
  /** The platform-facing label, e.g. in the operator's firm list. */
  name: z.string().min(1).max(200),
  /** Short label; also the fallback root for the firm's document archive. */
  shortName: z.string().min(1).max(40),

  primaryDomain: hostname,

  /** Validated against the live invoice_prefix pattern before insert. */
  invoicePrefix: z.string().min(1).transform((v) => v.trim().toUpperCase()),

  admin: z.object({
    // Normalise before validating: an address pasted out of a spreadsheet
    // arrives with a trailing space and mixed case, and neither is a reason to
    // stop provisioning.
    email: z
      .string()
      .transform((v) => v.trim().toLowerCase())
      .pipe(z.string().email()),
    name: z.string().min(1).max(200),
    position: z.string().max(120).default(''),
  }),

  branding: z.object({
    /**
     * Required, all three. lib/pdf/brand.ts throws at render on an unset
     * palette, document name, or font set — so a firm provisioned without them
     * is a firm whose first branded document fails, days later, in front of a
     * client. Better to refuse the config.
     */
    documentName: z.string().min(1).max(200),
    palette: z.object({ primary: hex, accent: hex }),
    nameLines: z.array(z.string().max(120)).max(3).default([]),
    tagline: z.string().max(200).default(''),
    fontSet: z.string().min(1).default('standard'),
  }),

  email: z
    .object({
      fromName: z.string().max(200).default(''),
      fromAddress: z.string().max(200).default(''),
      financeAddress: z.string().max(200).default(''),
      ipAddress: z.string().max(200).default(''),
      complianceAddress: z.string().max(200).default(''),
      ownedDomains: z.array(hostname).default([]),
    })
    // Spelled out, not `{}`: a Zod default short-circuits the object's own
    // field defaults, so an omitted `email` block would arrive with undefined
    // members and read as a missing config rather than an empty one.
    .default({
      fromName: '',
      fromAddress: '',
      financeAddress: '',
      ipAddress: '',
      complianceAddress: '',
      ownedDomains: [],
    }),

  /**
   * Names a live archive: changing one later does not move what is already
   * filed there, so it is set once here and left alone. Blank derives from the
   * short name.
   */
  documents: z
    .object({
      financeRoot: z.string().max(200).default(''),
      corporateRoot: z.string().max(200).default(''),
    })
    .default({ financeRoot: '', corporateRoot: '' }),

  /**
   * The entitlement half of the feature guard — what this firm is signed up
   * for. It does not switch anything on: every `firm_integrations` row is
   * written disabled regardless, so an operator still turns each one on once
   * its credentials are in. Default empty: an unlisted feature is off.
   */
  features: z.array(z.enum(FEATURE_KEYS)).default([]),
});

export type ProvisionConfig = z.infer<typeof provisionConfigSchema>;

/** Formats a Zod failure as one message per bad field, path included. */
export function formatConfigErrors(error: z.ZodError): string {
  return error.issues
    .map((issue) => `  ${issue.path.join('.') || '(root)'}: ${issue.message}`)
    .join('\n');
}

export class ProvisionConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ProvisionConfigError';
  }
}

export function parseProvisionConfig(raw: unknown): ProvisionConfig {
  const result = provisionConfigSchema.safeParse(raw);
  if (!result.success) {
    throw new ProvisionConfigError(
      `The provisioning config is not valid:\n${formatConfigErrors(result.error)}`,
    );
  }
  return result.data;
}

/**
 * Check a value against a CHECK-constraint pattern read from the database.
 *
 * The point is the message. A slug of "Acme Legal" inserted straight would come
 * back as `23514 new row for relation "firms" violates check constraint
 * "firms_slug_check"` — after the config parsed, which reads as a bug in the
 * script rather than a typo in the file.
 */
export function assertMatchesPattern(
  value: string,
  pattern: string,
  label: string,
  hint: string,
): void {
  if (new RegExp(pattern).test(value)) return;
  throw new ProvisionConfigError(
    `${label} "${value}" does not match what the database will accept.\n` +
      `  required shape: ${pattern}\n` +
      `  ${hint}`,
  );
}

export const SLUG_HINT =
  'Lowercase letters, digits and hyphens; 2–31 characters; must start with a letter or digit. e.g. "acme-legal"';

export const INVOICE_PREFIX_HINT =
  'Upper-case letters and digits only, 2–8 characters. It is the leading segment of every invoice number, e.g. "ACME" → ACME-2026-08-001';

/**
 * Where the firm's own content is filed. Mirrors `documentRoot()` in
 * lib/firm/config.ts so the summary can print what the app will derive.
 */
export function derivedDocumentRoot(config: ProvisionConfig, kind: 'finance' | 'corporate'): string {
  const configured =
    kind === 'finance' ? config.documents.financeRoot : config.documents.corporateRoot;
  if (configured.trim()) return configured.trim();
  return `${config.shortName} ${kind === 'finance' ? 'Finance' : 'Corporate'}`;
}

/** `firms.settings.features` — the entitlement map, absent keys meaning off. */
export function entitlementMap(config: ProvisionConfig): Record<string, boolean> {
  return Object.fromEntries(config.features.map((key) => [key, true]));
}
