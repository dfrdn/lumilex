export interface EntityConfig {
  dbTable: string;
  labelSingular: string;
  labelPlural: string;
  fields: EntityFieldConfig[];
  /** If set, this entity is a virtual view of another table with fixed server-side filters */
  viewOf?: string;
  /** Fixed filters applied server-side for virtual views (e.g., filings = deliverables with deadline + case) */
  fixedFilters?: Record<string, string>;
  /** If true, rows cannot be added/deleted from this view (it's read-only derived data) */
  readOnly?: boolean;
  /**
   * Primary key column for this table. Defaults to 'notion_id' for legacy
   * Notion-synced tables; in-app tables created with SERIAL ids should set
   * this to 'id'. Used by the admin entity API for PATCH/DELETE targeting.
   */
  primaryKeyColumn?: string;
}

