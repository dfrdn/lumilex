export interface EntityFieldConfig {
  key: string;
  label: string;
  supabaseColumn: string;
  type:
    | 'text'
    | 'date'
    | 'datetime'
    | 'select'
    | 'number'
    | 'checkbox'
    | 'people'
    | 'relation'
    | 'relation_multi'
    | 'files';
  editable: boolean;
  required?: boolean;
  options?: string[];
  relationEntity?: string;
  /**
   * For relation_multi: when set, only rows of the target entity whose
   * `scopeByField` value matches the CURRENT row's `scopeByField` value are
   * offered as options (e.g., scopeByField: 'client_id' on a matters
   * relation_multi gives you only other matters under the same client).
   * The target entity is expected to also have that column.
   */
  scopeByField?: string;
  /**
   * For relation / relation_multi: when set, only options whose notion_id
   * appears in the CURRENT row's array column of this name are offered.
   * Used for Parent Matter, where the candidate pool is the matter's own
   * related_matter_ids (same connected cluster) rather than every matter
   * under the same client.
   */
  scopeByRowArray?: string;
  width?: string;
  /** If true, value is auto-generated server-side (hidden from add form, shown as read-only) */
  autoGenerated?: boolean;
  /** If true, field is hidden from the Add row modal */
  hideFromAdd?: boolean;
  /** Default value when creating a new row */
  defaultValue?: string;
  /** For people fields: true = multiple selection (array), false = single */
  peopleMultiple?: boolean;
  /** For conditional visibility in add modal: only show if this other field has a value */
  showWhenField?: string;
  /** Optional companion to showWhenField: only show when that field equals one of these values. If omitted, any non-empty value passes. */
  showWhenValue?: string | string[];
  /** Client-side format validation applied in the add/edit modal */
  validate?: 'email' | 'phone';
  /**
   * Whether this field should be included in the server-side search OR
   * clause. Defaults to true for text/relation/select types. Set to false
   * for columns whose Postgres type is not text-ilike-compatible (e.g.
   * date[] stored under a `text` field config for rendering purposes).
   */
  searchable?: boolean;
}

