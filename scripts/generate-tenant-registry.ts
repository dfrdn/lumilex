import './load-env';
import './probe-websocket';
import * as fs from 'fs';
import * as path from 'path';
import { getSupabase } from '../lib/supabase';

/**
 * Regenerates lib/tenancy/tables.generated.ts from the live schema.
 *
 * Source of truth is the service-role-only RPC public.tenant_tables()
 * (migration 20260823_tenant_registry_rpc.sql): every public BASE TABLE
 * with a firm_id column. Tables on the fixed global list below are global
 * even when they carry firm_id (firm_domains does — it maps hostnames TO
 * firms, so callers filter it explicitly), so they are subtracted from the
 * tenant set to keep the two sets disjoint.
 *
 * Views come from public.view_exposure() (20260925_view_exposure_rpc.sql).
 * Every public view must carry firm_id: the facade scopes a view read the way
 * it scopes a table read, and refuses writes through one. A view without
 * firm_id is refused here rather than listed as global — a global view over
 * tenant tables is a service-role read that no firm pins, which is how
 * `filings` answered for every firm by id.
 *
 * Run after any migration that adds or drops a table:
 *   npx tsx scripts/generate-tenant-registry.ts
 */

const GLOBAL_TABLES = [
  'agents',
  // Who asked to open the public demo; belongs to no tenant (lib/demo/access.ts).
  'demo_access_requests',
  'drafting_idempotency',
  'firm_domains',
  'firms',
  'ph_holidays',
  // The platform operator identity is deliberately firm-less (see
  // 20260824_platform_operators.sql). tenant_tables() therefore never returns
  // it, and without a listing here the fail-closed facade throws on it.
  'platform_operators',
  'rule_deadlines',
  'rule_sets',
];

function toSetLiteral(names: string[]): string {
  return names.map((n) => `  '${n}',`).join('\n');
}

async function main() {
  const supabase = getSupabase();
  const { data, error } = await supabase.rpc('tenant_tables');
  if (error) throw new Error(`tenant_tables() failed: ${error.message}`);

  const globals = new Set(GLOBAL_TABLES);
  const tenantTables = (data as string[])
    .filter((name) => !globals.has(name))
    .sort();
  if (tenantTables.length === 0) throw new Error('tenant_tables() returned no tables');

  const { data: views, error: viewsErr } = await supabase.rpc('view_exposure');
  if (viewsErr) throw new Error(`view_exposure() failed: ${viewsErr.message}`);
  const viewRows = views as { view_name: string; has_firm_id: boolean }[];
  const unscopable = viewRows.filter((v) => !v.has_firm_id).map((v) => v.view_name);
  if (unscopable.length > 0) {
    throw new Error(
      `public views without a firm_id column cannot be firm-scoped: ${unscopable.join(', ')} — ` +
        'add firm_id to the view (see 20260925_views_security_invoker.sql)',
    );
  }
  const tenantViews = viewRows.map((v) => v.view_name).sort();

  const globalNames = [...GLOBAL_TABLES].sort();

  const output = `// AUTO-GENERATED by scripts/generate-tenant-registry.ts — do not edit.
// Regenerate after any migration that adds or drops a table:
//   npx tsx scripts/generate-tenant-registry.ts

/** Tables with a firm_id column — every query must be firm-scoped. */
export const TENANT_TABLES: ReadonlySet<string> = new Set([
${toSetLiteral(tenantTables)}
]);

/** Views with a firm_id column — reads are firm-scoped, writes are refused. */
export const TENANT_VIEWS: ReadonlySet<string> = new Set([
${toSetLiteral(tenantViews)}
]);

/** Firm-agnostic tables — queried as-is, no firm scoping. */
export const GLOBAL_TABLES: ReadonlySet<string> = new Set([
${toSetLiteral(globalNames)}
]);
`;

  const outPath = path.resolve(__dirname, '..', 'lib', 'tenancy', 'tables.generated.ts');
  const previous = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf-8') : null;
  fs.writeFileSync(outPath, output);
  console.log(
    `${previous === output ? 'Unchanged' : 'Wrote'} ${path.relative(process.cwd(), outPath)}: ` +
      `${tenantTables.length} tenant tables, ${tenantViews.length} tenant views, ${globalNames.length} global tables`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
